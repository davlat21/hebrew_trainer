// ======================================================
// Получить известные варианты.
// ======================================================

function getKnownTranscriptions(hebrew) {
    const clean = String(hebrew || "")
        .replace(/[^\u0590-\u05FF]/g, "");

    return HEBREW_TRANSCRIPTIONS[clean] || [];
}


// ======================================================
// Добавить вариант во время работы программы.
// Не сохраняет его постоянно — постоянное обучение
// находится в learning.js.
// ======================================================

function addRuntimeTranscription(hebrew, transcription) {
    const cleanHebrew = String(hebrew || "")
        .replace(/[^\u0590-\u05FF]/g, "");

    const cleanTranscription = String(transcription || "").trim();

    if (!cleanHebrew || !cleanTranscription) {
        return;
    }

    if (!HEBREW_TRANSCRIPTIONS[cleanHebrew]) {
        HEBREW_TRANSCRIPTIONS[cleanHebrew] = [];
    }

    const exists = HEBREW_TRANSCRIPTIONS[cleanHebrew]
        .some(function (item) {
            return item.toLowerCase() === cleanTranscription.toLowerCase();
        });

    if (!exists) {
        HEBREW_TRANSCRIPTIONS[cleanHebrew].push(cleanTranscription);
    }
}