const RUSSIAN_WORDS = new Set(
    RUSSIAN_WORD_FREQUENCY.keys()
);

function getRussianWordFrequency(word) {
    const clean = String(word || "")
        .toLowerCase()
        .replace(/ё/g, "е")
        .replace(/[^а-я]/g, "");

    return RUSSIAN_WORD_FREQUENCY.get(clean) || 0;
}

function isKnownRussianWord(word) {
    const clean = String(word || "")
        .toLowerCase()
        .replace(/ё/g, "е")
        .replace(/[^а-я]/g, "");

    return RUSSIAN_WORDS.has(clean);
}